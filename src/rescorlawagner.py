import random

def generate_rescorla_wagner_sequence(tmax, pval, alpha=0.5, rng=None):
    """
    Generate one reward sequence using a Rescorla-Wagner style update.
    Generate an input sequence of length tmax, where each sample is from a bernoulli with probability pval.
    The output sequence is generated by a Rescorla-Wagner update rule. 
    start with A0 = 0.5, and update using At = At-1 + alpha * (rt - At-1), where rt is the reward at time t
    """
    a_prev = 0.5
    a_vals = []
    rewards = []

    for _ in range(tmax):
        r_t = 1 if rng.random() < pval else 0
        rewards.append(r_t)
        a_prev = a_prev + alpha * (r_t - a_prev)
        # Clamp to keep association strength non-negative.
        a_prev = max(0.0, min(a_prev, 1.0))
        a_vals.append(a_prev)

    return (rewards, a_vals)

def generate_sequences(tmax, num_sequences, alpha=0.5, seed=None):
    """
    Generate multiple input/target pairs for the task, sample pval from a uniform distribution for each sequence
    """
    rng = random.Random(seed)
    pairs = []
    for _ in range(num_sequences):
        pval = rng.uniform(0.0, 1.0)
        pairs.append(generate_rescorla_wagner_sequence(tmax, pval, alpha=alpha, rng=rng))
    return pairs

